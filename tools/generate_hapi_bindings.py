#!/usr/bin/env python3
"""
Generate a runtime function table for the Houdini Engine C API (HAPI).

Why: the old Maxon bridge was locked to one exact Houdini build because it
linked libHAPIL directly. The Maya/Unreal/Max plugins all avoid that by
resolving every HAPI_* symbol at runtime with dlsym/GetProcAddress. This
script parses HAPI.h / HAPI_Helpers.h and emits an X-macro list that
src/hapi_core/HapiLibrary.{h,cpp} expands into typedefs, a function-pointer
table and a loader. Re-run it whenever you move to a newer Houdini:

    python3 tools/generate_hapi_bindings.py "$HFS/toolkit/include/HAPI" \
        src/hapi_core/HapiFunctions.inc

Only the declarations are parsed; the headers themselves are not copied.
Symbols missing from an older libHAPIL simply resolve to nullptr, so the
plugin can degrade gracefully instead of failing to load.
"""
import re
import sys
import os
import datetime

DECL_RE = re.compile(
    r'(?P<kind>HAPI_DECL_RETURN\s*\(\s*(?P<ret>[^)]+?)\s*\)|HAPI_DECL_DEPRECATED_REPLACE\s*\([^)]*\)|HAPI_DECL_DEPRECATED\s*\([^)]*\)|HAPI_DECL)'
    r'\s+(?P<name>HAPI_[A-Za-z0-9_]+)\s*\((?P<args>[^;]*?)\)\s*;',
    re.S)


def strip_comments(text):
    text = re.sub(r'/\*.*?\*/', '', text, flags=re.S)
    text = re.sub(r'//[^\n]*', '', text)
    return text


def normalise_args(args):
    args = ' '.join(args.split())
    if args in ('', 'void'):
        return 'void'
    return args


def parse(path):
    with open(path, 'r', encoding='utf-8', errors='replace') as f:
        text = strip_comments(f.read())
    out = []
    for m in DECL_RE.finditer(text):
        kind = m.group('kind')
        ret = m.group('ret') or 'HAPI_Result'
        ret = ' '.join(ret.split())
        name = m.group('name')
        args = normalise_args(m.group('args'))
        deprecated = 'DEPRECATED' in kind
        out.append((name, ret, args, deprecated))
    return out


def main():
    if len(sys.argv) != 3:
        sys.stderr.write(__doc__)
        return 2
    inc_dir, out_path = sys.argv[1], sys.argv[2]
    headers = [os.path.join(inc_dir, 'HAPI.h'), os.path.join(inc_dir, 'HAPI_Helpers.h')]
    funcs = []
    seen = set()
    for h in headers:
        if not os.path.exists(h):
            sys.stderr.write('missing header: %s\n' % h)
            return 1
        for f in parse(h):
            if f[0] in seen:
                continue
            seen.add(f[0])
            funcs.append(f)
    funcs.sort(key=lambda f: f[0])

    version = {}
    vpath = os.path.join(inc_dir, 'HAPI_Version.h')
    if os.path.exists(vpath):
        for line in open(vpath):
            m = re.match(r'#define\s+(HAPI_VERSION_\w+)\s+(\d+)', line)
            if m:
                version[m.group(1)] = m.group(2)

    with open(out_path, 'w') as o:
        o.write('// GENERATED by tools/generate_hapi_bindings.py -- do not edit by hand.\n')
        o.write('// Source headers: %s\n' % os.path.abspath(inc_dir))
        if version:
            o.write('// Houdini %s.%s.%s / HAPI %s.%s.%s\n' % (
                version.get('HAPI_VERSION_HOUDINI_MAJOR', '?'),
                version.get('HAPI_VERSION_HOUDINI_MINOR', '?'),
                version.get('HAPI_VERSION_HOUDINI_BUILD', '?'),
                version.get('HAPI_VERSION_HOUDINI_ENGINE_MAJOR', '?'),
                version.get('HAPI_VERSION_HOUDINI_ENGINE_MINOR', '?'),
                version.get('HAPI_VERSION_HOUDINI_ENGINE_API', '?')))
        o.write('// Generated: %s\n' % datetime.date.today().isoformat())
        o.write('// Usage: #define HAPI_FUNC(name, ret, args) ... then #include this file.\n')
        o.write('//   name: symbol without the HAPI_ prefix, ret: return type,\n')
        o.write('//   args: parenthesised parameter list. Deprecated entries use HAPI_FUNC_DEPRECATED\n')
        o.write('//   (defaults to HAPI_FUNC when not defined).\n\n')
        o.write('#ifndef HAPI_FUNC_DEPRECATED\n#define HAPI_FUNC_DEPRECATED HAPI_FUNC\n#endif\n\n')
        for name, ret, args, dep in funcs:
            short = name[len('HAPI_'):]
            macro = 'HAPI_FUNC_DEPRECATED' if dep else 'HAPI_FUNC'
            o.write('%s(%s, %s, (%s))\n' % (macro, short, ret, args))
        o.write('\n#undef HAPI_FUNC_DEPRECATED\n')
    sys.stderr.write('wrote %d functions to %s\n' % (len(funcs), out_path))
    return 0


if __name__ == '__main__':
    sys.exit(main())
